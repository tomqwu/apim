def validated_output_path(output: Path) -> Path:
    """Return a safe output path before any recursive replacement occurs."""
    lexical = output if output.is_absolute() else ROOT / output
    if lexical.is_symlink():
        raise SystemExit(f"Refusing symlinked site output: {lexical}")
    resolved = lexical.resolve()
    default = DEFAULT_OUTPUT.resolve()
    if resolved == default:
        if resolved.exists():
            sentinel = resolved / OUTPUT_SENTINEL
            if not resolved.is_dir() or not sentinel.is_file() or sentinel.read_text(encoding="utf-8") != OUTPUT_SENTINEL_VALUE:
                raise SystemExit(f"Refusing to replace an existing unowned output directory: {resolved}")
        return resolved
    if resolved == Path(resolved.anchor) or ROOT.is_relative_to(resolved):
        raise SystemExit(f"Refusing site output that contains the repository: {resolved}")
    if resolved.is_relative_to(ROOT):
        raise SystemExit(f"Only {DEFAULT_OUTPUT} may be replaced inside the repository: {resolved}")
    if resolved.exists():
        sentinel = resolved / OUTPUT_SENTINEL
        if not resolved.is_dir() or not sentinel.is_file() or sentinel.read_text(encoding="utf-8") != OUTPUT_SENTINEL_VALUE:
            raise SystemExit(f"Refusing to replace an existing unowned output directory: {resolved}")
    return resolved


def build(output: Path) -> None:
    if not SITE_SOURCE.exists():
        raise SystemExit(f"Site source is missing: {SITE_SOURCE}")
    output = validated_output_path(output)
    revision = source_revision()
    dirty = source_is_dirty(revision)
    timestamp = generated_at(revision)
    candidates = repository_candidate_paths()
    content_sources = publishable_content_sources(candidates)
    asset_sources = site_asset_sources(candidates)
    if output.exists():
        shutil.rmtree(output)
    output.mkdir(parents=True)
    for source in asset_sources:
        destination = output / source.relative_to(SITE_SOURCE)
        destination.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(source, destination)
    (output / OUTPUT_SENTINEL).write_text(OUTPUT_SENTINEL_VALUE, encoding="utf-8")
    shutil.copy2(output / "index.html", output / "404.html")
    items = collect_items(output, content_sources)
    stats = build_stats(items)
    visuals = build_visuals(items)
    validate_site_projection(stats, visuals)
    presentation = make_presentation(items, stats, visuals)
    manifest = {
        "schemaVersion": MANIFEST_SCHEMA_VERSION,
        "sourceRevision": revision,
        "sourceDirty": dirty,
        "generatedAt": timestamp,
        "generator": {
            "path": MANIFEST_GENERATOR,
            "sha256": sha256_file(ROOT / MANIFEST_GENERATOR),
        },
        "site": {"title": "API Management Studies", "description": "A living research, architecture, comparison, and proof-of-concept library."},
        "assets": asset_digests(output, asset_sources),
        "stats": stats,
        "visuals": visuals,
        "audiences": build_audiences(items, stats, visuals, presentation),
        "items": items,
        "presentation": presentation,
    }
    (output / "content-manifest.json").write_text(json.dumps(manifest, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    (output / ".nojekyll").touch()
    state = "dirty" if dirty else "clean"
    print(f"Built {output} with {len(items)} resources from {revision} ({state})")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT, help="Output directory")
    args = parser.parse_args()
    output = args.output if args.output.is_absolute() else ROOT / args.output
    build(output)


if __name__ == "__main__":
    main()
