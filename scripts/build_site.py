def run_git(*args: str) -> str:
    """Return one Git value or fail with a provenance-specific message."""
    try:
        result = subprocess.run(
            ("git", *args),
            cwd=ROOT,
            check=True,
            capture_output=True,
            text=True,
        )
    except (FileNotFoundError, subprocess.CalledProcessError) as exc:
        detail = getattr(exc, "stderr", "") or str(exc)
        raise SystemExit(f"Unable to resolve site provenance with git {' '.join(args)}: {detail.strip()}") from exc
    return result.stdout.strip()


def safe_path_location(name: str) -> str:
    """Return a log-safe location without reflecting hostile path text."""
    return f"path-sha256:{hashlib.sha256(name.encode('utf-8', errors='surrogatepass')).hexdigest()[:16]}"


def reject_hidden_index_flags() -> None:
    """Reject Git flags that can hide worktree bytes from clean-state checks."""
    result = subprocess.run(
        ("git", "ls-files", "-v", "-z"),
        cwd=ROOT, check=False, stdout=subprocess.PIPE, stderr=subprocess.PIPE,
    )
    if result.returncode:
        raise SystemExit("Unable to inspect Git index visibility flags")
    for entry in (value for value in result.stdout.split(b"\0") if value):
        marker = entry[:1]
        if marker == b"S" or marker.islower():
            raise SystemExit("Refusing a build while Git index visibility flags hide worktree state")


def repository_candidate_paths() -> list[Path]:
    """Return tracked plus non-ignored untracked paths without newline ambiguity."""
    reject_hidden_index_flags()
    result = subprocess.run(
        ("git", "ls-files", "-c", "-o", "--exclude-standard", "-z"),
        cwd=ROOT, check=False, stdout=subprocess.PIPE, stderr=subprocess.PIPE,
    )
    if result.returncode:
        raise SystemExit("Unable to enumerate public build inputs with git ls-files")
    try:
        names = [value.decode("utf-8") for value in result.stdout.split(b"\0") if value]
    except UnicodeDecodeError as exc:
        raise SystemExit("Refusing a non-UTF-8 public build path") from exc
    candidates: list[Path] = []
    for name in names:
        if not name or name != name.strip() or any(unicodedata.category(character).startswith("C") for character in name):
            raise SystemExit("Refusing a public build path containing control or surrounding whitespace")
        path = ROOT / name
        if path.is_symlink():
            raise SystemExit(f"Refusing symlinked public build input at {safe_path_location(name)}")
        candidate = ROOT
        for part in Path(name).parts:
            candidate /= part
            if candidate.is_symlink():
                raise SystemExit(f"Refusing public build input below a symlink at {safe_path_location(name)}")
        if path.is_file():
            candidates.append(path)
    return sorted(set(candidates))


def publishable_content_sources(candidates: list[Path] | None = None) -> list[Path]:
    sources: list[Path] = []
    for source in candidates or repository_candidate_paths():
        relative = source.relative_to(ROOT)
        if not relative.parts or relative.parts[0] not in CONTENT_ROOTS:
            continue
        if any(part.startswith(".") for part in relative.parts):
            continue
        if source.suffix.lower() in TEXT_EXTENSIONS | MEDIA_EXTENSIONS or source.name == "Dockerfile":
            sources.append(source)
    return sources


def site_asset_sources(candidates: list[Path] | None = None) -> list[Path]:
    return [
        source for source in (candidates or repository_candidate_paths())
        if source.relative_to(ROOT).parts[:1] == ("site",)
    ]


def source_revision() -> str:
    """Resolve the built commit in an explicit, CI-safe priority order."""
    candidate = os.environ.get("SOURCE_REVISION") or os.environ.get("GITHUB_SHA") or "HEAD"
    revision = run_git("rev-parse", "--verify", f"{candidate}^{{commit}}")
    if not re.fullmatch(r"[0-9a-f]{40,64}", revision):
        raise SystemExit(f"Resolved source revision is not a full Git object ID: {revision!r}")
    return revision


def source_is_dirty(revision: str) -> bool:
    """Mark raw-byte changes and revision/checkout mismatches as non-reproducible."""
    head = run_git("rev-parse", "--verify", "HEAD^{commit}")
    worktree_changes = run_git("status", "--porcelain=v1", "--untracked-files=all")
    return bool(worktree_changes) or revision != head or not raw_tracked_bytes_match(revision)


def raw_tracked_bytes_match(revision: str) -> bool:
    """Compare worktree bytes with Git blobs without clean/smudge filters."""
    listed = subprocess.run(
        ("git", "ls-files", "-c", "-z"), cwd=ROOT, check=False,
        stdout=subprocess.PIPE, stderr=subprocess.PIPE,
    )
    if listed.returncode:
        raise SystemExit("Unable to enumerate tracked files for raw-byte provenance")
    try:
        names = [value.decode("utf-8") for value in listed.stdout.split(b"\0") if value]
    except UnicodeDecodeError as exc:
        raise SystemExit("Refusing a non-UTF-8 tracked path during raw-byte provenance") from exc
    for name in names:
        path = ROOT / name
        if not path.is_file() or path.is_symlink():
            return False
        expected = subprocess.Popen(
            ("git", "cat-file", "blob", f"{revision}:{name}"), cwd=ROOT,
            stdout=subprocess.PIPE, stderr=subprocess.DEVNULL,
        )
        expected_digest = hashlib.sha256()
        assert expected.stdout is not None
        for chunk in iter(lambda: expected.stdout.read(1024 * 1024), b""):
            expected_digest.update(chunk)
        expected.stdout.close()
        if expected.wait() != 0:
            return False
        if sha256_file(path) != expected_digest.hexdigest():
            return False
    return True


def generated_at(revision: str) -> str:
    """Derive build time from reproducible inputs, never the wall clock."""
    epoch_value = os.environ.get("SOURCE_DATE_EPOCH")
    if epoch_value is None:
        epoch_value = run_git("show", "-s", "--format=%ct", revision)
    try:
        epoch = int(epoch_value)
        if epoch < 0:
            raise ValueError
    except ValueError as exc:
        raise SystemExit(f"SOURCE_DATE_EPOCH must be a non-negative integer, got {epoch_value!r}") from exc
    try:
        return datetime.fromtimestamp(epoch, tz=timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")
    except (OverflowError, OSError, ValueError) as exc:
        raise SystemExit(f"SOURCE_DATE_EPOCH is outside the supported timestamp range: {epoch_value!r}") from exc


def sha256_file(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for chunk in iter(lambda: handle.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def asset_digests(output: Path, sources: list[Path] | None = None) -> dict[str, dict[str, object]]:
    assets: dict[str, dict[str, object]] = {}
    source_assets = {path.relative_to(SITE_SOURCE).as_posix() for path in (sources or site_asset_sources())}
    asset_paths = source_assets | {"404.html"}
    missing = REQUIRED_SITE_ASSET_PATHS - asset_paths
    if missing:
        raise SystemExit(f"Required site asset definitions are missing: {sorted(missing)}")
    for relative in sorted(asset_paths):
        path = output / relative
        if not path.is_file():
            raise SystemExit(f"Required site asset is missing: {path}")
        assets[relative] = {"sha256": sha256_file(path), "size": path.stat().st_size}
    return assets


def slug(value: str) -> str:
    value = re.sub(r"[^a-z0-9]+", "-", value.lower()).strip("-")
    return value or "document"


def safe_text(path: Path) -> str:
    if path.suffix.lower() not in TEXT_EXTENSIONS and path.name != "Dockerfile":
        return ""
    try:
        text = path.read_text(encoding="utf-8")
    except (UnicodeDecodeError, OSError) as exc:
        raise SystemExit(f"Refusing unreadable/non-UTF-8 public text source: {path.relative_to(ROOT)}") from exc
    if "\0" in text:
        raise SystemExit(f"Refusing NUL-containing public text source: {path.relative_to(ROOT)}")
    return text


def clean_inline(value: str) -> str:
    value = re.sub(r"!\[[^\]]*\]\([^)]*\)", "", value)
    value = re.sub(r"\[([^\]]+)\]\([^)]*\)", r"\1", value)
    value = re.sub(r"[`*_>#|]", " ", value)
    return re.sub(r"\s+", " ", value).strip(" -")


def document_title(path: Path, text: str) -> str:
    if path.suffix.lower() == ".md":
        heading = re.search(r"^#\s+(.+)$", text, flags=re.MULTILINE)
        if heading:
            return clean_inline(heading.group(1))
    if path.suffix.lower() in {".yaml", ".yml"}:
        info_title = re.search(r"^\s{2}title:\s*[\"']?(.+?)[\"']?\s*$", text, flags=re.MULTILINE)
        if info_title:
            return clean_inline(info_title.group(1))
    return re.sub(r"^\d{2,4}[-_]", "", path.stem).replace("-", " ").replace("_", " ").title()


def document_summary(path: Path, text: str, title: str) -> str:
    if path.suffix.lower() == ".md":
        # Repository control markers (study contracts, diagram provenance, and
        # other HTML comments) are machine-readable metadata, not article copy.
        # Remove complete comments before selecting the first visible paragraph
        # so they cannot leak into cards or search results.
        visible_text = re.sub(r"<!--[\s\S]*?-->", "", text)
        blocks = re.split(r"\n\s*\n", visible_text)
        for block in blocks:
            candidate = clean_inline(block)
            if not candidate or candidate == title or block.lstrip().startswith(("#", "```", "|")):
                continue
            return candidate[:260] + ("…" if len(candidate) > 260 else "")
    if path.suffix.lower() == ".mmd":
        return f"Source diagram for {title}. Open it in the architecture gallery to render the model."
    if path.suffix.lower() == ".csv":
        return f"Structured dataset for {title}, available as a filterable table and download."
    if path.suffix.lower() in {".yaml", ".yml"} and re.search(r"^openapi:\s*", text, flags=re.MULTILINE):
        return f"OpenAPI contract for {title}."
    return f"Repository resource: {title}."


def item_type(path: Path, text: str) -> str:
    suffix = path.suffix.lower()
    if suffix in {".yaml", ".yml"} and re.search(r"^openapi:\s*", text, flags=re.MULTILINE):
        return "openapi"
    if path.name == "Dockerfile":
        return "dockerfile"
    return TYPE_NAMES.get(suffix, "resource")


def item_order(path: Path) -> int:
    match = re.match(r"^(\d+)", path.name)
    return int(match.group(1)) if match else 9999


def make_tags(relative: Path, text: str, section: str) -> list[str]:
    haystack = f"{relative.as_posix()}\n{text[:30000]}".lower()
    tags = [section.lower()]
    for label, needles in TAG_RULES.items():
        if any(needle in haystack for needle in needles):
            tags.append(label)
    return list(dict.fromkeys(tags))[:7]


def collect_items(output: Path, sources: list[Path] | None = None) -> list[dict[str, object]]:
    items: list[dict[str, object]] = []
    seen_ids: set[str] = set()
    by_root: dict[str, list[Path]] = {root_name: [] for root_name in CONTENT_ROOTS}
    for source in sources or publishable_content_sources():
        by_root[source.relative_to(ROOT).parts[0]].append(source)
    for root_name in CONTENT_ROOTS:
        for source in sorted(by_root[root_name]):
            relative = source.relative_to(ROOT)
            destination = output / "content" / relative
            destination.parent.mkdir(parents=True, exist_ok=True)
            shutil.copy2(source, destination)
            text = safe_text(source)
            title = document_title(source, text)
            section = SECTION_LABELS[root_name]
            kind = item_type(source, text)
            item_id = slug(relative.with_suffix("").as_posix())
            if item_id in seen_ids:
                item_id = f"{item_id}-{len(items)}"
            seen_ids.add(item_id)
            search_text = clean_inline(text[:50000])
            items.append(
                {
                    "id": item_id,
                    "title": title,
                    "path": relative.as_posix(),
                    "contentUrl": f"content/{relative.as_posix()}",
                    "route": f"#/doc/{item_id}",
                    "section": section,
                    "type": kind,
                    "order": item_order(source),
                    "tags": make_tags(relative, text, section),
                    "summary": document_summary(source, text, title),
                    "searchText": search_text,
                    "size": source.stat().st_size,
                    "sha256": sha256_file(source),
                }
            )
    items.sort(key=lambda item: (CONTENT_ROOTS.index(str(item["path"]).split("/", 1)[0]), int(item["order"]), str(item["title"])))
    by_path = {str(item["path"]): item for item in items}
    for diagram_path, companion_path in DIAGRAM_COMPANIONS.items():
        diagram = by_path.get(diagram_path)
        companion = by_path.get(companion_path)
        if diagram and companion:
            diagram["companionId"] = companion["id"]
            diagram["companionPath"] = companion_path
    return items


