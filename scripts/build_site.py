    def stable_ids(value: str, *, deduplicate: bool = True) -> list[str]:
        """Expand semicolon-separated stable IDs and inclusive ``ID..ID`` ranges."""
        values: list[str] = []
        for raw_part in value.split(";"):
            part = clean_inline(raw_part)
            if not part:
                continue
